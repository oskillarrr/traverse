var reNonID = regexp.MustCompile(`[^A-Za-z0-9_]`)

func ident(prefix, s string) string { return prefix + reNonID.ReplaceAllString(s, "_") }

func q(s string) string { return strings.ReplaceAll(strings.ReplaceAll(s, `"`, "'"), "\n", " ") }

// MermaidLayers renders the package graph grouped by layer.
func MermaidLayers(f *model.Facts, maxNodes int, lang string) string {
	stats := topPackages(f, maxNodes)
	keep := map[string]string{}
	var b strings.Builder
	b.WriteString("%% Generated by Traverse. Edit freely; regenerate to refresh.\nflowchart LR\n")
	for _, l := range scan.LayerOrder {
		var in []model.PackageStat
		for _, s := range stats {
			if s.Layer == l {
				in = append(in, s)
			}
		}
		if len(in) == 0 {
			continue
		}
		fmt.Fprintf(&b, "  subgraph %s[\"%s\"]\n", ident("L_", l), q(tr(lang, l)))
		for _, s := range in {
			id := ident("p_", s.Package)
			keep[s.Package] = id
			fmt.Fprintf(&b, "    %s[\"%s (%d)\"]\n", id, q(s.Package), s.Types)
		}
		b.WriteString("  end\n")
	}
	for _, e := range packageEdges(f) {
		a, ok1 := keep[e[0]]
		c, ok2 := keep[e[1]]
		if ok1 && ok2 {
			fmt.Fprintf(&b, "  %s --> %s\n", a, c)
		}
	}
	return b.String()
}

func topPackages(f *model.Facts, n int) []model.PackageStat {
	stats := append([]model.PackageStat{}, f.PackageStats...)
	sort.Slice(stats, func(i, j int) bool {
		if stats[i].Types != stats[j].Types {
			return stats[i].Types > stats[j].Types
		}
		return stats[i].Package < stats[j].Package
	})
	if len(stats) > n {
		stats = stats[:n]
	}
	return stats
}

func packageEdges(f *model.Facts) [][2]string {
	comp := map[string]model.Component{}
	for _, c := range f.Components {
		comp[c.FQN] = c
	}
	set := map[[2]string]bool{}
	for _, d := range f.Dependencies {
		a, b := comp[d.From].Package, comp[d.To].Package
		if a != b && a != "" && b != "" {
			set[[2]string{a, b}] = true
		}
	}
	var out [][2]string
	for k := range set {
		out = append(out, k)
	}
	sort.Slice(out, func(i, j int) bool { return out[i][0]+out[i][1] < out[j][0]+out[j][1] })
	return out
}

// MermaidLandscape renders systems and typed relationships.
func MermaidLandscape(p *model.Portfolio) string {
	var b strings.Builder
	b.WriteString("%% Generated by Traverse\nflowchart LR\n")
	groups := map[string][]model.System{}
	var gnames []string
	for _, s := range p.Systems {
		if _, ok := groups[s.Group]; !ok {
			gnames = append(gnames, s.Group)
		}
		groups[s.Group] = append(groups[s.Group], s)
	}
	for _, g := range gnames {
		if g != "" {
			fmt.Fprintf(&b, "  subgraph %s[\"%s\"]\n", ident("g_", g), q(g))
		}
		for _, s := range groups[g] {
			fmt.Fprintf(&b, "    %s[\"%s\"]\n", ident("s_", s.Name), q(s.Name))
		}
		if g != "" {
			b.WriteString("  end\n")
		}
	}
	for _, l := range p.Links {
		arrow, label := "-->", fmt.Sprintf("%s %d", l.Kind, l.Count)
		if l.Kind == "library" || strings.HasPrefix(l.Kind, "shared") || l.Confidence == "low" {
			arrow = "-.->"
		}
		if l.Confidence == "low" {
			label += " (low confidence)"
		}
		fmt.Fprintf(&b, "  %s %s|\"%s\"| %s\n", ident("s_", l.From), arrow, q(label), ident("s_", l.To))
	}
	return b.String()
}

// StructurizrRepo renders a C4 model (Structurizr DSL) for one system:
// containers are build modules, components are layers within each module.
func StructurizrRepo(f *model.Facts, lang string) string {
	var b strings.Builder
	sys := ident("sys_", f.Repo.Name)
	fmt.Fprintf(&b, "// Generated by Traverse %s. Static analysis: validate before publishing.\nworkspace \"%s\" {\n  model {\n", f.Tool.Version, q(f.Repo.Name))
	fmt.Fprintf(&b, "    %s = softwareSystem \"%s\" {\n", sys, q(f.Repo.Name))
	depKind := map[string]string{}
	for _, d := range f.Deployables {
		depKind[d.Module] = strings.ToUpper(d.Kind)
	}
	comp := map[string]model.Component{}
	modLayers := map[string]map[string]int{}
	for _, c := range f.Components {
		comp[c.FQN] = c
		if c.SourceSet != "main" {
			continue
		}
		if modLayers[c.Module] == nil {
			modLayers[c.Module] = map[string]int{}
		}
		modLayers[c.Module][c.Layer]++
	}
	// Components outside any build module (repositories without build files,
	// e.g. mainframe sources) get a synthetic container so the model is valid.
	containers := append([]model.Module{}, f.Modules...)
	known := map[string]bool{}
	for _, m := range f.Modules {
		known[m.ID] = true
	}
	for mod := range modLayers {
		if !known[mod] {
			known[mod] = true
			name := mod
			if name == "" {
				name = f.Repo.Name + " (sources without build descriptor)"
			}
			containers = append(containers, model.Module{ID: mod, Name: name, Build: "none"})
		}
	}
	sort.Slice(containers[len(f.Modules):], func(i, j int) bool {
		return containers[len(f.Modules)+i].ID < containers[len(f.Modules)+j].ID
	})
	for _, m := range containers {
		tech := strings.TrimSpace(m.Build + " " + m.Packaging + " " + m.Runtime)
		if k, ok := depKind[m.ID]; ok {
			tech += " · deploys " + k
		}
		fmt.Fprintf(&b, "      %s = container \"%s\" \"%s\" \"%s\" {\n", ident("c_", m.ID), q(m.Name), q(m.ID), q(tech))
		for _, l := range scan.LayerOrder {
			if n := modLayers[m.ID][l]; n > 0 {
				fmt.Fprintf(&b, "        %s = component \"%s\" \"%d types\" \"%s\"\n", ident("k_", m.ID+"_"+l), q(tr(lang, l)), n, l)
			}
		}
		b.WriteString("      }\n")
	}
	b.WriteString("    }\n")
	// external elements from contracts
	ext := map[string]bool{}
	for _, c := range f.Contracts {
		if c.Direction == "calls" || c.Kind == "db-table" || c.Kind == "jms" {
			key := c.Kind
			if !ext[key] {
				ext[key] = true
				fmt.Fprintf(&b, "    %s = softwareSystem \"External %s\" \"Detected %s dependencies\" \"External\"\n", ident("x_", key), q(strings.ToUpper(key)), q(key))
			}
		}
	}
	rels := map[string]bool{}
	for _, d := range f.Dependencies {
		a, c := comp[d.From], comp[d.To]
		if a.SourceSet != "main" || c.SourceSet != "main" || (a.Module == c.Module && a.Layer == c.Layer) {
			continue
		}
		k := ident("k_", a.Module+"_"+a.Layer) + " -> " + ident("k_", c.Module+"_"+c.Layer)
		if !rels[k] {
			rels[k] = true
			fmt.Fprintf(&b, "    %s \"uses\"\n", k)
		}
	}
	for _, m := range f.Modules {
		for _, d := range m.Deps {
			for _, m2 := range f.Modules {
				if d.ID == m2.ID && m2.ID != m.ID && !d.Managed {
					fmt.Fprintf(&b, "    %s -> %s \"depends on\" \"%s\"\n", ident("c_", m.ID), ident("c_", m2.ID), q(d.Kind))
				}
			}
		}
	}
	extKeys := make([]string, 0, len(ext))
	for key := range ext {
		extKeys = append(extKeys, key)
	}
	sort.Strings(extKeys)
	for _, key := range extKeys {
		fmt.Fprintf(&b, "    %s -> %s \"%s\"\n", sys, ident("x_", key), q(key))
	}
	containerOf := map[string]string{}
	for _, m := range containers {
		containerOf[m.ID] = ident("c_", m.ID)
	}
	depModel, depViews := structurizrDeployment(f, sys, containerOf)
	b.WriteString(depModel)
	fmt.Fprintf(&b, "  }\n  views {\n    systemContext %s \"Context\" {\n      include *\n      autoLayout lr\n    }\n    container %s \"Containers\" {\n      include *\n      autoLayout lr\n    }\n", sys, sys)
	for _, v := range depViews {
		b.WriteString(v)
	}
	for _, m := range containers {
		if len(modLayers[m.ID]) > 0 {
			fmt.Fprintf(&b, "    component %s \"%s\" {\n      include *\n      autoLayout lr\n    }\n", ident("c_", m.ID), ident("Components_", firstNonEmpty(m.ID, "sources")))
		}
	}
	b.WriteString("    styles {\n      element \"External\" {\n        background #999999\n      }\n    }\n  }\n}\n")
	return b.String()
}

// StructurizrLandscape renders the portfolio as a C4 system landscape.
func StructurizrLandscape(p *model.Portfolio) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// Generated by Traverse %s. Static analysis: validate before publishing.\nworkspace \"Portfolio\" {\n  model {\n", p.Tool.Version)
	groups := map[string][]model.System{}
	var gnames []string
	for _, s := range p.Systems {
		if _, ok := groups[s.Group]; !ok {
			gnames = append(gnames, s.Group)
		}
		groups[s.Group] = append(groups[s.Group], s)
	}
	for _, g := range gnames {
		ind := "    "
		if g != "" {
			fmt.Fprintf(&b, "    group \"%s\" {\n", q(g))
			ind = "      "
		}
		for _, s := range groups[g] {
			fmt.Fprintf(&b, "%s%s = softwareSystem \"%s\" \"%s\"\n", ind, ident("s_", s.Name), q(s.Name), q(strings.Join(s.Languages, ", ")))
		}
		if g != "" {
			b.WriteString("    }\n")
		}
	}
	for _, l := range p.Links {
		tags := l.Kind
		if l.Confidence == "low" {
			tags += ",low-confidence"
		}
		fmt.Fprintf(&b, "    %s -> %s \"%s (%d)\" \"%s\" \"%s\"\n", ident("s_", l.From), ident("s_", l.To), q(l.Kind), l.Count, q(strings.Join(firstStrs(l.Keys, 3), ", ")), q(tags))
	}
	b.WriteString("  }\n  views {\n    systemLandscape \"Landscape\" {\n      include *\n      autoLayout lr\n    }\n    styles {\n")
	b.WriteString("      relationship \"library\" {\n        dashed true\n        color #888888\n      }\n      relationship \"shared-db\" {\n        dashed true\n        color #c9372c\n      }\n      relationship \"low-confidence\" {\n        dashed true\n        opacity 40\n      }\n    }\n  }\n}\n")
	return b.String()
}

// PlantUMLLandscape renders C4-PlantUML using the stdlib bundled in plantuml.jar (offline).
func PlantUMLLandscape(p *model.Portfolio) string {
	var b strings.Builder
	b.WriteString("@startuml\n' Generated by Traverse. Uses the C4 stdlib bundled with PlantUML (no network).\n!include <C4/C4_Context>\nLAYOUT_LEFT_RIGHT()\nAddRelTag(\"low\", $lineStyle = DashedLine(), $textColor = \"#8a96a6\", $lineColor = \"#b8c0cc\", $legendText = \"low confidence\")\n")
	for _, s := range p.Systems {
		fmt.Fprintf(&b, "System(%s, \"%s\", \"%s\")\n", ident("s_", s.Name), q(s.Name), q(strings.Join(s.Languages, ", ")))
	}
	for _, l := range p.Links {
		if l.Confidence == "low" {
			fmt.Fprintf(&b, "Rel(%s, %s, \"%s (%d)\", $tags=\"low\")\n", ident("s_", l.From), ident("s_", l.To), q(l.Kind), l.Count)
			continue
		}
		fmt.Fprintf(&b, "Rel(%s, %s, \"%s (%d)\")\n", ident("s_", l.From), ident("s_", l.To), q(l.Kind), l.Count)
	}
	b.WriteString("@enduml\n")
	return b.String()
}

func firstNonEmpty(xs ...string) string {
	for _, x := range xs {
		if x != "" {
			return x
		}
	}
	return ""
}
